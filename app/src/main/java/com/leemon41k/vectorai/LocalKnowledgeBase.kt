    fun findRelevant(question: String): String {
        val words = question.lowercase()
            .replace(Regex("[^\\p{L}\\p{N} ]"), " ")
            .split(Regex("\\s+"))
            .filter { it.length >= 3 }
            .toSet()
        if (words.isEmpty()) return ""
        return entries.map { entry ->
            val score = entry.keywords.count { keyword ->
                words.any { word -> word == keyword || word.startsWith(keyword) || keyword.startsWith(word) }
            }
            entry to score
        }.filter { it.second > 0 }
            .sortedByDescending { it.second }
            .take(2)
            .joinToString("\n\n") { it.first.text }
    }
